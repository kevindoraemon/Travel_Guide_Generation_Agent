# travel_planner —— 基于多智能体与自进化的旅游路书生成系统
#
# 核心架构：
#   - 协调官（Coordinator）：调度多个情报员子代理并行搜集，调用精修与评分完成"自进化"
#   - 情报员（Scout）：使用网络搜索搜集景点/交通/住宿/美食/门票/天气等情报
#   - 体验官（Critic）：对抗式挑刺，发现路书行程冲突/需求偏离/事实错误
#   - 评估器（Evaluator）：从可执行性/预算合理性/体验丰富度三维打分，驱动迭代修复
#   - 简报官（Briefing）：把用户出行需求整理为出行简报并起草路书
#
# 主入口：travel_planner.itinerary_builder
